"""Download + optimize card images listed in tools/images.json.

Usage:
    python3 -m venv .venv && .venv/bin/pip install Pillow
    .venv/bin/python tools/build_images.py            # only missing files
    .venv/bin/python tools/build_images.py --force    # rebuild all

Manifest key = "<deck>/<cardId>" -> img/<deck>/<cardId>.webp
  "file": "tools/art/x.png" 가 있으면 url 대신 그 파일을 쓴다 — 직접 손본
  그림(원본 SVG 는 같은 폴더)에 쓴다. url 은 출처 표기용으로 남는다.
  kind "photo": center-crop 4:3, 800x600 webp
  kind "icon" : keep alpha, max 256px webp
Also writes js/credits-data.js (attribution list shown on the Credits screen).
"""
import json, os, sys, time, urllib.request
from io import BytesIO
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "tools", "images.json")
UA = {"User-Agent": "korean-cards-image-builder/1.0"}


def fetch(url):
    for attempt in range(3):
        try:
            req = urllib.request.Request(url, headers=UA)
            with urllib.request.urlopen(req, timeout=60) as r:
                return r.read()
        except Exception as e:
            if attempt == 2:
                raise
            time.sleep(2 + attempt * 3)


def photo(im):
    im = im.convert("RGB")
    w, h = im.size
    target = 4 / 3
    if w / h > target:
        nw = int(h * target); x = (w - nw) // 2
        im = im.crop((x, 0, x + nw, h))
    else:
        nh = int(w / target); y = (h - nh) // 2
        im = im.crop((0, y, w, y + nh))
    return im.resize((800, 600), Image.LANCZOS) if im.width > 800 else im


def icon(im):
    im = im.convert("RGBA")
    im.thumbnail((256, 256), Image.LANCZOS)
    return im


def main():
    force = "--force" in sys.argv
    items = json.load(open(MANIFEST, encoding="utf-8"))
    failed = []
    for key, meta in items.items():
        out = os.path.join(ROOT, "img", key + ".webp")
        if os.path.exists(out) and not force:
            continue
        os.makedirs(os.path.dirname(out), exist_ok=True)
        try:
            if meta.get("file"):
                im = Image.open(os.path.join(ROOT, meta["file"]))
            else:
                im = Image.open(BytesIO(fetch(meta["url"])))
            im = photo(im) if meta["kind"] == "photo" else icon(im)
            im.save(out, "WEBP", quality=78, method=6)
            print("ok  ", key, os.path.getsize(out) // 1024, "KB")
        except Exception as e:
            failed.append(key)
            print("FAIL", key, e)

    credits = [{"key": k, **{f: v[f] for f in ("title", "author", "license", "licenseUrl", "source")}}
               for k, v in items.items()]
    out_js = os.path.join(ROOT, "js", "credits-data.js")
    with open(out_js, "w", encoding="utf-8", newline="\n") as f:  # Windows에서도 LF 고정
        f.write("/* generated by tools/build_images.py — do not edit */\n")
        f.write("window.IMAGE_CREDITS = " + json.dumps(credits, ensure_ascii=False, indent=1) + ";\n")
    if failed:
        print("\nfailed:", failed); sys.exit(1)


main()
